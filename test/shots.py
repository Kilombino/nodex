# Playwright smoke test + screenshots. Usage: shots.py [base_url] [out_dir]
import sys, json
from playwright.sync_api import sync_playwright
BASE = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:3230'
OUT = sys.argv[2] if len(sys.argv) > 2 else '/mnt/datos2/nodex-shots'
PK = '0222d36d7b634ead665c982145f6e4507ad65c4f369902ab3ca11e379d2139dc60'
errors, fails = [], []
def check(cond, msg):
    print(('OK   ' if cond else 'FAIL ') + msg)
    if not cond: fails.append(msg)
with sync_playwright() as p:
    b = p.chromium.launch()
    for mode, vp in [('desktop', {'width': 1366, 'height': 900}), ('mobile', {'width': 390, 'height': 844})]:
        ctx = b.new_context(viewport=vp, device_scale_factor=1 if mode == 'desktop' else 2, is_mobile=(mode == 'mobile'))
        # The site defaults to English; the first half of the run checks the Spanish UI.
        ctx.add_init_script("if (!localStorage.getItem('nodex.lang')) localStorage.setItem('nodex.lang', 'es')")
        pg = ctx.new_page()
        pg.on('console', lambda m: m.type == 'error' and errors.append(m.text))
        pg.on('pageerror', lambda e: errors.append(str(e)))
        pg.on('request', lambda r: (not r.url.startswith(BASE)) and errors.append('EXTERNAL REQUEST ' + r.url))
        def shot(name, full=True):
            pg.screenshot(path=f'{OUT}/{mode}-{name}.png', full_page=full)
        pg.goto(BASE + '/'); pg.wait_for_selector('.stat'); pg.wait_for_timeout(1200)
        check('Nodos' in pg.inner_text('main'), f'{mode} home ES has stats')
        check(pg.locator('.toplist li').count() >= 16, f'{mode} home top lists')
        check(pg.locator('#netchart svg').count() == 1, f'{mode} network chart')
        sw = pg.evaluate('document.documentElement.scrollWidth'); check(sw <= vp['width'] + 1, f'{mode} home no horizontal scroll ({sw})')
        shot('home-es')
        pg.goto(BASE + '/node/' + PK); pg.wait_for_selector('#chtable table'); pg.wait_for_timeout(1500)
        txt = pg.inner_text('main')
        check('Kilombino' in txt and 'Ficha del operador' in txt, f'{mode} node page + operator card')
        rows = pg.locator('#chtable tbody tr').count(); check(rows >= 30, f'{mode} node channels rows={rows}')
        check('.onion' in txt, f'{mode} node shows onion address')
        shot('node-es')
        pg.click('#chtable th[data-k=out]'); pg.wait_for_timeout(200)
        check(pg.locator('#chtable th.on[data-k=out]').count() == 1, f'{mode} channel table sorts')
        pg.goto(BASE + '/rankings'); pg.wait_for_selector('#rktable table'); pg.wait_for_timeout(500)
        check(pg.locator('#rktable tbody tr').count() >= 30, f'{mode} rankings rows')
        shot('rankings-es')
        pg.click('a.tab[href="/rankings/central"]'); pg.wait_for_timeout(400)
        first = pg.locator('#rktable tbody tr').first.inner_text(); print('   top central:', first.split('\n')[0:3])
        shot('rankings-central-es')
        pg.fill('#topsearch input', 'pyblock'); pg.press('#topsearch input', 'Enter'); pg.wait_for_timeout(1500)
        check('PyBLOCK' in pg.inner_text('main'), f'{mode} search alias')
        shot('search-es')
        pg.fill('#topsearch input', PK); pg.press('#topsearch input', 'Enter'); pg.wait_for_timeout(1500)
        check(PK in pg.url, f'{mode} search pubkey -> node page')
        pg.fill('#topsearch input', '976591x102x0'); pg.press('#topsearch input', 'Enter'); pg.wait_for_timeout(1500)
        check('/channel/' in pg.url and 'Paperclip' in pg.inner_text('main'), f'{mode} search channel -> channel page')
        shot('channel-es')
        pg.click('#lang'); pg.wait_for_timeout(1200)
        check('Channel' in pg.inner_text('main'), f'{mode} toggle EN on channel page')
        pg.goto(BASE + '/'); pg.wait_for_selector('.stat'); pg.wait_for_timeout(1000)
        check('Nodes' in pg.inner_text('main'), f'{mode} EN persisted on home')
        shot('home-en')
        pg.goto(BASE + '/node/' + PK); pg.wait_for_selector('#chtable table'); pg.wait_for_timeout(1500)
        check('Operator card' in pg.inner_text('main'), f'{mode} node EN')
        sw = pg.evaluate('document.documentElement.scrollWidth'); check(sw <= vp['width'] + 1, f'{mode} node no horizontal scroll ({sw})')
        shot('node-en')
        pg.goto(BASE + '/activity'); pg.wait_for_timeout(1200); shot('activity-en')
        # Splices: a spliced channel shows its history, and the old id says where it went.
        sl = json.loads(pg.evaluate("fetch('/data/graph.json').then(r => r.text())")).get('splice_log', [])
        if sl:
            check('recent splices' in pg.inner_text('main').lower(), f'{mode} activity lists splices')
            pg.goto(BASE + '/channel/' + sl[0]['live']); pg.wait_for_timeout(1200)
            txt = pg.inner_text('main')
            check('splice history' in txt.lower() and sl[0]['from']['short_id'] in txt, f'{mode} channel page splice history')
            sw = pg.evaluate('document.documentElement.scrollWidth'); check(sw <= vp['width'] + 1, f'{mode} channel no horizontal scroll ({sw})')
            shot('channel-splice-en')
            pg.goto(BASE + '/channel/' + sl[0]['from']['id']); pg.wait_for_timeout(1500)
            check('stays open as' in pg.inner_text('main'), f'{mode} old channel points to the spliced one')
            shot('channel-old-en')
        pg.click('#lang'); pg.wait_for_timeout(500)
        ctx.close()
    b.close()
print('console/page errors:', json.dumps(errors[:20], indent=1))
print('FAILS:', fails)
sys.exit(1 if fails or errors else 0)
